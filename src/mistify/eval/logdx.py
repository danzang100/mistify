"""LogDx-CI: end-to-end diagnosis quality, on incidents nobody here invented.

Every other eval case in this project is generated by this project. That makes them a good
regression suite and poor evidence: the answer was planted, the noise was planted to a
specification, and a run that finds the answer has cleared a bar somebody here also drew.
Templating escaped this by scoring against Loghub's annotated ground truth. The
investigation has not, until now.

LogDx-CI is 35 real GitHub Actions failures with author-verified diagnoses -- eight failure
categories across pytest, cargo, Go, Maven, Node, Docker and Kubernetes, from 27-line logs to
200k-line ones. It is the only public corpus found that scores the *outcome* of LLM log
diagnosis rather than the parsing step, which is exactly the axis this project has never been
measured on.

Each case carries `raw.log` and a `ground_truth.json` whose parts map onto the checks the
harness already runs:

* `required_signals` -- the lines a correct diagnosis must rest on. These become `must_cite`
  markers, so a claim has to be traceable to rows rather than merely worded well.
* `expected_diagnosis.must_not_claim` -- the wrong diagnoses that are *plausible* for this log.
  No public dataset scores whether a verification pass catches a plausible-but-wrong
  conclusion. This is the closest thing to one, and it is the reason this
  corpus is worth more here than a bigger pile of logs would be.
* `expected_diagnosis.must_mention` -- terms a correct conclusion names.

Two things measured rather than assumed, both of which changed the design:

**Markers resolve against events, not only templates.** A signal like a failing test's path is
the *variable* part of its line, so Drain3 replaces it with a wildcard and the marker cannot be
found in any template pattern. On the first case tried, two of six critical signals were
invisible to a pattern search and present in the event text. So resolution reads events and
maps back to their templates.

**Not every signal is a marker.** `exit_code` carries the value `"1"`, which occurs in a
thousand lines of a CI log and resolves to whatever template happens to hold it first. A check
built on it passes for free, which is worse than not running it. Signals are admitted on
distinctiveness, and what gets dropped is recorded on the case rather than quietly skipped.

Data is downloaded on demand into `.cache/` and never committed. LogDx-CI's cases are CC-BY-4.0
and its code Apache-2.0, so redistribution is permitted with attribution -- but a corpus
vendored into a repository is a licence question this project has consistently declined to
answer, and the same reasoning that keeps Loghub out keeps this out.
"""

