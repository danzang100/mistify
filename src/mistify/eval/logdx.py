LOGDX_SPLITS: tuple[str, ...] = tuple(LOGDX_CASES)

#: Signal types that are not log text and cannot be searched for. Only one, and it earns its
#: place: `exit_code` carries values like `"1"`, which occur in a thousand unrelated lines of a
#: CI log, so a citation check built on it passes for free. A check that cannot fail is worse
#: than no check -- it contributes a passing row to a scorecard while measuring nothing.
#:
#: This was an allowlist of the types worth keeping, and that was wrong. Surveying all 35 cases
#: turned up thirteen types, and the allowlist silently dropped `compile_error` -- whose values
#: run to a median of 104 characters and are the most distinctive strings in the corpus. An
#: allowlist has to be right about a vocabulary it does not control; a blocklist of the one
#: type that is definitionally not text does not.
_NON_TEXT_TYPES = frozenset({"exit_code"})

#: Shortest string admitted as a marker, whatever its type. The backstop that needs to know
#: nothing about the vocabulary: across the corpus, `failed_test`, `command`, `assertion`,
#: `package` and `version` all have members down to six or eight characters, and a six-character
#: marker matches half a build log. Twelve is long enough to exclude those and short enough to
#: keep real exception names.
_MIN_MARKER_LENGTH = 12


@dataclass(frozen=True, slots=True)
class LogDxCase:
    """One LogDx-CI case: where its log is, and what a correct diagnosis of it says."""

    case_id: str
    split: str
    log_path: Path
    repo: str
    framework: str
    failure_category: str
    root_cause: str
    #: Distinctive strings from the critical `required_signals`, usable as citation markers.
    markers: tuple[str, ...]
    #: Signals dropped as too common to search for, kept so the omission is visible.
    dropped_signals: tuple[str, ...]
    must_mention: tuple[str, ...]
    must_not_claim: tuple[str, ...]
    line_count: int


_ANSI = re.compile("\x1b\\[[0-9;]*[A-Za-z]")


def _strip_ansi(text: str) -> str:
    return _ANSI.sub("", text)


def split_of(case_id: str) -> str:
    """Which split a case belongs to, or a `ValueError` naming the ones that exist."""
    for split, ids in LOGDX_CASES.items():
        if case_id in ids:
            return split
    known = ", ".join(sorted(i for ids in LOGDX_CASES.values() for i in ids))
    raise ValueError(f"unknown LogDx-CI case {case_id!r}. Known: {known}")


def logdx_case_ids(split: str | None = None) -> tuple[str, ...]:
    """Case ids in one split, or every case when `split` is None."""
    if split is None:
        return tuple(i for ids in LOGDX_CASES.values() for i in ids)
    if split not in LOGDX_CASES:
        raise ValueError(f"unknown split {split!r}. Known: {', '.join(LOGDX_SPLITS)}")
    return LOGDX_CASES[split]


def fetch_logdx_case(case_id: str, directory: Path) -> Path:
    """Download one case into `directory/<split>/<case_id>`, or return the copy on disk.

    Per file rather than per case, so an interrupted download resumes instead of restarting:
    the stress cases run to hundreds of thousands of lines and re-fetching a 200 MB log because
    the metadata beside it failed is a poor trade.
    """
    split = split_of(case_id)
    target = directory / split / case_id
    target.mkdir(parents=True, exist_ok=True)
    for name in _CASE_FILES:
        path = target / name
        if path.exists() and path.stat().st_size > 0:
            continue
        url = _RAW.format(split=split, case_id=case_id, name=name)
        with urllib.request.urlopen(url, timeout=120) as response:
            path.write_bytes(response.read())
    return target


def _present_in(log_path: Path, marker: str) -> bool:
    """Whether the log actually contains this marker, ignoring terminal escape sequences.

    Ground truth is transcribed from a log as a person reads it, and a CI log is written for a
    terminal. In one tokio case 71.9% of the lines carry ANSI colour codes, so the ground truth
    says `tests-build::macros compile_fail_full` where the file says
    `\\x1b[35;1mtests-build::macros\\x1b[0m \\x1b[34;1mcompile_fail_full\\x1b[0m`. Comparing the
    two literally finds nothing.

    The stronger reason to check at all: some ground-truth values are not in the log in any
    form. `396 tests run: 395 passed, 1 failed, 1 skipped` appears nowhere in the file it
    annotates. A check built on a string the corpus does not contain can only ever fail, and it
    fails looking exactly like a wrong answer from the investigation.
    """
    text = _strip_ansi(log_path.read_text(encoding="utf-8", errors="replace"))
    return _strip_ansi(marker) in text


def _markers_from(ground_truth: dict[str, Any]) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Critical signals split into usable markers and the ones dropped as too common.

    Only `critical` signals become markers. `important` ones are real evidence, but requiring
    every one of them turns a citation check into a completeness check, and an investigation
    that found the root cause and cited four of five supporting lines has not failed.
    """
    markers: list[str] = []
    dropped: list[str] = []
    for signal in ground_truth.get("required_signals", []):
        if not isinstance(signal, dict):
            continue
        if signal.get("importance") != "critical":
            continue
        # `stack_location` carries its string in `file`; the rest carry it in `value`.
        value = signal.get("value") or signal.get("file") or ""
        text = str(value).strip()
        kind = str(signal.get("type", "signal"))
        # Why it was dropped, not just that it was. "too common to search for" was printed over
        # a 104-character compile error that had merely failed a type allowlist, which reads as
        # a statement about the corpus when it was a statement about this file.
        if kind in _NON_TEXT_TYPES:
            dropped.append(f"{kind} (not log text): {text[:40]}")
            continue
        if len(text) < _MIN_MARKER_LENGTH:
            dropped.append(f"{kind} (too short to identify a line): {text[:40]}")
            continue
        markers.append(text)
    return tuple(markers), tuple(dropped)


def load_logdx_case(case_dir: Path) -> LogDxCase:
    """Read a downloaded case directory into the parts the harness scores against."""
    case = json.loads((case_dir / "case.json").read_text(encoding="utf-8"))
    ground_truth = json.loads((case_dir / "ground_truth.json").read_text(encoding="utf-8"))

    markers, dropped = _markers_from(ground_truth)

    # A marker the log does not contain cannot be cited by anything, so a check built on it can
    # only ever fail -- and it fails looking exactly like a wrong answer from the investigation.
    # Dropped here, and said out loud, because a scorecard that counts unscorable rows against
    # the model is reporting its own corpus defects as model error.
    log_path = case_dir / "raw.log"
    if log_path.exists():
        present = tuple(m for m in markers if _present_in(log_path, m))
        absent = [m for m in markers if m not in present]
        dropped = dropped + tuple(f"absent from the log: {m[:50]}" for m in absent)
        markers = present

    diagnosis = ground_truth.get("expected_diagnosis") or {}
    root_cause = (ground_truth.get("root_cause") or {}).get("summary", "")

    return LogDxCase(
        case_id=str(case.get("case_id", case_dir.name)),
        split=case_dir.parent.name,
        log_path=case_dir / "raw.log",
        repo=str(case.get("repo", "unknown")),
        framework=str(case.get("framework", "unknown")),
        failure_category=str(case.get("failure_category", "unknown")),
        root_cause=str(root_cause),
        markers=markers,
        dropped_signals=dropped,
        must_mention=tuple(str(m) for m in diagnosis.get("must_mention", [])),
        must_not_claim=tuple(str(m) for m in diagnosis.get("must_not_claim", [])),
        line_count=int(case.get("line_count", 0)),
    )


def _fixed_source(path: Path) -> Callable[[Path], Path]:
    """An `EvalCase.source` that returns an already-downloaded file.

    A named factory rather than a lambda with a default argument: the corpus file is shared and
    read-only, so the run directory the harness offers has nothing to do -- and binding the path
    through a closure keeps the signature honest about ignoring it.
    """

    def source(_directory: Path) -> Path:
        return path

    return source


def logdx_eval_cases(
    split: str | None = "dev", cache: Path = Path(".cache/logdx")
) -> tuple[Any, ...]:
    """Build `EvalCase`s for a split, downloading whatever is not already cached.

    Imported lazily by the harness rather than at module import, because building these
    performs network I/O and `mistify eval --list` must work offline for the cases that need
    no corpus at all.
    """
    from mistify.eval.cases import EvalCase

    cases = []
    for case_id in logdx_case_ids(split):
        loaded = load_logdx_case(fetch_logdx_case(case_id, cache))
        notes = [
            f"{loaded.repo} · {loaded.framework} · {loaded.failure_category} · "
            f"{loaded.line_count} lines.",
            f"Ground truth: {loaded.root_cause[:200]}",
        ]
        if loaded.dropped_signals:
            # Said out loud. A signal silently dropped is a check the scorecard implies and
            # never ran, which is the way a suite comes to overstate what it measured.
            notes.append("Signals not checked: " + "; ".join(loaded.dropped_signals))
        cases.append(
            EvalCase(
                name=f"logdx-{loaded.case_id}",
                summary=f"{loaded.repo}: {loaded.failure_category} in CI ({loaded.framework}).",
                # The corpus file is read-only and shared, so the run directory the harness
                # offers is ignored: copying a 200k-line log per run buys nothing.
                source=_fixed_source(loaded.log_path),
                expects_incident=True,
                must_cite=loaded.markers,
                must_mention=loaded.must_mention,
                must_not_claim=loaded.must_not_claim,
                external=True,
                notes=tuple(notes),
            )
        )
    return tuple(cases)
